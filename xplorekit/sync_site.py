"""Hand the verified data to the private site repo.

  python -m xplorekit.sync_site --site-dir ../site [--dest public/data] [--pr-body pr.md]

Mirrors data/<section>/*.json (entries + index.json) into <site-dir>/<dest>/<section>/ and writes <dest>/index.json (a manifest
with no counts). The destination folder is fully generated, so files that no longer exist here are removed there.
Rejected items are never copied. It only touches files; the workflow does the git branch and pull request.
"""
import argparse
import json
import sys
from pathlib import Path

from xplorekit.common import ROOT, load_json, save_json, settings, today


def fact_checked(entry):
    return any(str(v).startswith("fact_check:") for v in entry.get("verified", []))


def sync(data_dir, site_dir, dest="public/data"):
    """Mirror verified data into the site checkout. Only entries that carry a fact-check tag are delivered; the folder is fully generated."""
    site = Path(site_dir)
    if not (site / "public").is_dir() or not (site / "wrangler.jsonc").exists():
        raise SystemExit(f"{site} does not look like the Xplorekit site repo (no public/ or wrangler.jsonc): refusing to write")
    target = site / dest
    added, changed, removed = [], [], []
    manifest = {"generated_at": today(), "sections": {}}

    def put(path, data_bytes, label):
        if not path.exists():
            added.append(label)
        elif path.read_bytes() != data_bytes:
            changed.append(label)
        path.write_bytes(data_bytes)

    for section in settings()["sections"]:
        src = Path(data_dir) / section
        dst = target / section
        dst.mkdir(parents=True, exist_ok=True)
        want, ids = {}, set()
        for p in sorted(src.glob("*.json")) if src.exists() else []:
            if p.name == "index.json":
                continue
            e = load_json(p, {})
            if fact_checked(e):  # never ship an entry nobody fact-checked
                want[p.name] = p
                ids.add(e.get("id"))
        for name, p in want.items():
            put(dst / name, p.read_bytes(), f"{section}/{name}")
        idx = load_json(src / "index.json", {}) if src.exists() else {}
        idx["items"] = [i for i in idx.get("items", []) if i.get("id") in ids]
        put(dst / "index.json", (json.dumps(idx, indent=2, ensure_ascii=False) + "\n").encode(), f"{section}/index.json")
        for q in dst.glob("*.json"):
            if q.name not in want and q.name != "index.json":
                q.unlink()
                removed.append(f"{section}/{q.name}")
        manifest["sections"][section] = f"/{dest.removeprefix('public/')}/{section}/index.json"
    save_json(target / "index.json", manifest)
    return added, changed, removed


def pr_body(data_dir, added, changed, removed):
    lines = ["Automated research update from the public collector repo. When every safety check below passes it merges itself, and merging deploys to the live site. If it is still open, a check failed or auto-merge is off, and a human needs to look.", ""]
    new = [a for a in added if not a.endswith("index.json")]
    if new:
        lines.append(f"### New entries ({len(new)})")
        for a in new:
            section, name = a.split("/", 1)
            e = load_json(Path(data_dir) / section / name, {})
            title = e.get("title") or e.get("name") or name
            lines.append(f"- **{section}** · {title} · score {e.get('quality_score')} · checks: {', '.join(e.get('verified', []))}")
            lines.append(f"  - source: {e.get('source_url')}")
            inc = e.get("income")
            if inc:
                lines.append(f"  - income: {'stated by source, ' + str(inc['low']) + '-' + str(inc['high']) + ' ' + inc['currency'] + '/' + inc['period'] if inc['stated_in_source'] else 'no figure (source states none)'}")
        lines.append("")
    upd = [c for c in changed if not c.endswith("index.json")]
    if upd:
        lines.append(f"### Updated entries ({len(upd)})")
        lines += [f"- {c}" for c in upd] + [""]
    if removed:
        lines.append(f"### Removed ({len(removed)})")
        lines += [f"- {r}" for r in removed] + [""]
    lines += ["Only entries with an independent fact-check are delivered.", "", "Generated by the xplorekit-dashboard pipeline."]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--site-dir", required=True)
    ap.add_argument("--data-dir", default=str(ROOT / settings().get("data_dir", "data")))
    ap.add_argument("--dest", default="public/data")
    ap.add_argument("--pr-body")
    a = ap.parse_args(argv)
    added, changed, removed = sync(a.data_dir, a.site_dir, a.dest)
    print(f"added={len(added)} changed={len(changed)} removed={len(removed)}")
    if a.pr_body:
        Path(a.pr_body).write_text(pr_body(a.data_dir, added, changed, removed), "utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
